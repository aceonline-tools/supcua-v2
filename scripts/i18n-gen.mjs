// Generates frontend/src/i18n/ids.gen.ts (message id and parameter types) from locale/catalog.json.
// Usage: node scripts/i18n-gen.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const textOf = (t) => (typeof t === 'string' ? [t] : Object.values(t));
const paramsOf = (e) => [...new Set(textOf(e.en).flatMap((s) => [...s.matchAll(/\{([A-Za-z_][A-Za-z0-9_]*)\}/g)].map((m) => m[1])))].sort();

/** The text of ids.gen.ts for a catalogue object: web-scoped ids only. */
export function generate(catalog) {
  const web = Object.keys(catalog).filter((id) => (catalog[id].scope ?? ['web']).includes('web')).sort();
  const lines = ['// Code generated by scripts/i18n-gen.mjs from locale/catalog.json; DO NOT EDIT.', '', 'export interface MsgParams {'];
  for (const id of web) {
    const fields = paramsOf(catalog[id]).map((p) => `${p}: ${p === 'n' ? 'number' : 'string | number'}`).join('; ');
    lines.push(fields ? `  '${id}': { ${fields} };` : `  '${id}': {};`);
  }
  lines.push('}', '', 'export type MsgId = keyof MsgParams;', '');
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const catalog = JSON.parse(fs.readFileSync(path.join(root, 'locale/catalog.json'), 'utf8'));
  const target = path.join(root, 'frontend/src/i18n/ids.gen.ts');
  const out = generate(catalog);
  if (process.argv.includes('--check')) {
    if ((fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '') !== out) {
      console.error('ids.gen.ts is stale: run `npm run i18n:gen` in frontend/');
      process.exit(1);
    }
  } else fs.writeFileSync(target, out);
}
